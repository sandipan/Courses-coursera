	/**
	 * Get the number of vertices (road intersections) in the graph
	 * @return The number of vertices in the graph.
	 */
	public int getNumVertices() {
		return nodes.size();
	}
	
	/**
	 * Return the intersections, which are the vertices in this graph.
	 * @return The vertices in this graph as GeographicPoints
	 */
	public Set<GeographicPoint> getVertices() {
		return nodes.keySet();
	}
	
	/**
	 * Get the number of road segments in the graph
	 * @return The number of edges in the graph.
	 */
	public int getNumEdges() {
		return nodes.values().parallelStream()
				.mapToInt(node -> node.getEdges().size())
				.sum();
	}

	
	
	/** Add a node corresponding to an intersection at a Geographic Point
	 * If the location is already in the graph or null, this method does 
	 * not change the graph.
	 * @param location  The location of the intersection
	 * @return true if a node was added, false if it was not (the node
	 * was already in the graph, or the parameter is null).
	 */
	public boolean addVertex(GeographicPoint location) {
		return location != null && nodes.putIfAbsent(location, new MapNode(location)) == null;
	}
	
	/**
	 * Adds a directed edge to the graph from pt1 to pt2.  
	 * Precondition: Both GeographicPoints have already been added to the graph
	 * @param from The starting point of the edge
	 * @param to The ending point of the edge
	 * @param roadName The name of the road
	 * @param roadType The type of the road
	 * @param length The length of the road, in km
	 * @throws IllegalArgumentException If the points have not already been
	 *   added as nodes to the graph, if any of the arguments is null,
	 *   or if the length is less than 0.
	 */
	public void addEdge(GeographicPoint from, GeographicPoint to, String roadName,
			String roadType, double length) throws IllegalArgumentException {
		if (from == null || to == null || roadName == null || roadType == null) {
			throw new IllegalArgumentException("Null arguments was found. " +
			"[from = " + from + ", to = " + to + ", roadName = " + roadName + ", roadType = " + roadType);
		}

		if (!nodes.containsKey(from)) {
			throw new IllegalArgumentException("From node was not found");
		}

		if (!nodes.containsKey(to)) {
			throw new IllegalArgumentException("To node was not found");
		}

		if (length < 0) {
			throw new IllegalArgumentException("Invalid edge length ");
		}

		MapNode nodeFrom = nodes.get(from);
		MapNode nodeTo = nodes.get(to);
		nodeFrom.addEdge(new MapEdge(nodeFrom, nodeTo, roadName, roadType, length));
	}
	

