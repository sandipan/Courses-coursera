	/** Find the path from start to goal using breadth first search
	 * 
	 * @param start The starting location
	 * @param goal The goal location
	 * @param nodeSearched A hook for visualization.  See assignment instructions for how to use it.
	 * @return The list of intersections that form the shortest (unweighted)
	 *   path from start to goal (including both start and goal).
	 */
	public List<GeographicPoint> bfs(GeographicPoint start, GeographicPoint goal,
									 Consumer<GeographicPoint> nodeSearched) {

		if (start == null || goal == null) {
			return null;
		}
		// init
		Map<MapNode, MapNode> parent = new HashMap<>();
		MapNode startNode = nodes.get(start);
		MapNode goalNode = nodes.get(goal);

		boolean found = bfsSearch(startNode, goalNode, nodeSearched, parent);
		if (!found) {
			return null;
		}

		return constructPath(startNode, goalNode, parent);
	}

	private boolean bfsSearch(MapNode start, MapNode end,
						Consumer<GeographicPoint> nodeSearched, Map<MapNode, MapNode> parentMap) {
		boolean found = false;
		LinkedList<MapNode> queue = new LinkedList<>();
		Set<MapNode> visited = new HashSet<>();

		queue.addLast(start);
		visited.add(start);

		while (!queue.isEmpty()) {
			MapNode curr = queue.pollFirst();
			if (curr == end) {
				found = true;
				break;
			}
			curr.getEdges().stream()
					.filter(edge -> !visited.contains(edge.getTo()))
					.forEach(edge -> {
						visited.add(edge.getTo());
						parentMap.put(edge.getTo(), curr);
						queue.addLast(edge.getTo());
					});
			nodeSearched.accept(curr.getLocation());
		}
		return found;
	}

	private List<GeographicPoint> constructPath(MapNode start, MapNode goal, Map<MapNode, MapNode> parentMap) {
		LinkedList<GeographicPoint> path = new LinkedList<>();
		MapNode curr = goal;
		while (curr != start) {
			path.addFirst(curr.getLocation());
			curr = parentMap.get(curr);
		}
		path.addFirst(start.getLocation());
		return path;
	}

